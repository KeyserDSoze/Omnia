/**
 * OAuth connector callback relay. The provider redirects a POPUP to /connections/callback;
 * that page hands {state, code} to the Tao window that started the flow, which forwards them
 * to the API with its in-memory bearer token. The API binds the state to the signed actor and
 * redeems the code with the confidential client secret and PKCE verifier (never in the browser).
 *
 * BroadcastChannel (same-origin only) still works when the provider's
 * Cross-Origin-Opener-Policy severs window.opener; postMessage to the opener is a fallback.
 * Nothing is written to browser storage.
 */
export const CONNECTOR_CHANNEL = 'tao.connectors';
export const CONNECTOR_CALLBACK_TYPE = 'tao.connector.callback';

export type ConnectorCallback = {
  type: typeof CONNECTOR_CALLBACK_TYPE;
  state: string;
  code: string | null;
  error: string | null;
};

const STATE_PATTERN = /^[A-Za-z0-9_-]{16,128}$/;

export function parseConnectorCallback(search: string): ConnectorCallback | null {
  const params = new URLSearchParams(search);
  const state = params.get('state');
  if (!state || !STATE_PATTERN.test(state)) return null;
  const code = params.get('code');
  const error = params.get('error');
  if (code !== null && (code.length === 0 || code.length > 4096)) return null;
  if (code === null && error === null) return null;
  return {
    type: CONNECTOR_CALLBACK_TYPE,
    state,
    code,
    // Provider error codes are shown nowhere verbatim; keep a bounded identifier only.
    error: error === null ? null : (error.replace(/[^a-z_]/gi, '').slice(0, 64) || 'error')
  };
}

export function isConnectorCallback(data: unknown, expectedState: string): data is ConnectorCallback {
  if (typeof data !== 'object' || data === null) return false;
  const value = data as Partial<ConnectorCallback>;
  return value.type === CONNECTOR_CALLBACK_TYPE && value.state === expectedState &&
    (typeof value.code === 'string' || typeof value.error === 'string');
}

/** The state is generated by the API and embedded in the provider authorization URL. */
export function stateFromAuthorizationUrl(url: string): string | null {
  try {
    const parsed = new URL(url);
    const state = parsed.searchParams.get('state');
    return parsed.protocol === 'https:' && state !== null && STATE_PATTERN.test(state) ? state : null;
  } catch {
    return null;
  }
}

type MessageTarget = Pick<EventTarget, 'addEventListener' | 'removeEventListener'>;

export function waitForConnectorCallback(expectedState: string, options: {
  origin: string;
  timeoutMs: number;
  signal?: AbortSignal;
  target?: MessageTarget;
  channel?: () => MessageTarget & { close(): void } | null;
}): Promise<ConnectorCallback> {
  return new Promise((resolve, reject) => {
    const target = options.target ?? (globalThis as unknown as MessageTarget);
    const channel = (options.channel ?? (() => typeof BroadcastChannel === 'function'
      ? new BroadcastChannel(CONNECTOR_CHANNEL) : null))();
    let settled = false;
    const finish = (action: () => void) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      channel?.removeEventListener('message', onChannel);
      channel?.close();
      target.removeEventListener('message', onWindow);
      options.signal?.removeEventListener('abort', onAbort);
      action();
    };
    const accept = (data: unknown) => {
      if (isConnectorCallback(data, expectedState)) finish(() => resolve(data));
    };
    const onChannel = (event: Event) => accept((event as MessageEvent).data);
    const onWindow = (event: Event) => {
      const message = event as MessageEvent;
      if (message.origin === options.origin) accept(message.data);
    };
    const onAbort = () => finish(() => reject(new Error('aborted')));
    const timer = setTimeout(() => finish(() => reject(new Error('timeout'))), options.timeoutMs);
    channel?.addEventListener('message', onChannel);
    target.addEventListener('message', onWindow);
    if (options.signal?.aborted) onAbort();
    else options.signal?.addEventListener('abort', onAbort);
  });
}

export function publishConnectorCallback(callback: ConnectorCallback, origin: string,
  opener: { postMessage(message: unknown, targetOrigin: string): void } | null): void {
  if (typeof BroadcastChannel === 'function') {
    const channel = new BroadcastChannel(CONNECTOR_CHANNEL);
    channel.postMessage(callback);
    channel.close();
  }
  try {
    opener?.postMessage(callback, origin);
  } catch {
    // Opener gone or cross-origin after provider navigation: the channel already delivered.
  }
}
